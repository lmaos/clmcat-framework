package com.clmcat.basics.commons.tablec.split;

public class DatabaseSplitException extends RuntimeException {

	private static final long serialVersionUID = 1L;

	public DatabaseSplitException() {
		super();

	}

	public DatabaseSplitException(String message, Throwable cause, boolean enableSuppression,
			boolean writableStackTrace) {
		super(message, cause, enableSuppression, writableStackTrace);

	}

	public DatabaseSplitException(String message, Throwable cause) {
		super(message, cause);

	}

	public DatabaseSplitException(String message) {
		super(message);

	}

	public DatabaseSplitException(Throwable cause) {
		super(cause);

	}

}
